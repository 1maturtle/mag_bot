-- ======================================
-- Схема бази даних для Supabase (PostgreSQL)
-- Telegram-бот для домашніх завдань
-- ======================================
-- Відповідає структурі робочої бази, з якою працює database.py.
-- Потрібна лише для створення НОВОГО проєкту: SQL Editor → New query → Run.
-- CREATE TABLE IF NOT EXISTS не змінює вже існуючі таблиці.
-- ======================================


-- ── Таблиця користувачів ──────────────────────────────────────
-- id = Telegram ID користувача
CREATE TABLE IF NOT EXISTS users (
    id          BIGINT    PRIMARY KEY,
    username    TEXT,
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);


-- ── Таблиця завдань ───────────────────────────────────────────
-- deadline зберігається текстом у форматі "ДД.ММ.РРРР ГГ:ХХ"
CREATE TABLE IF NOT EXISTS tasks (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT REFERENCES users(id) ON DELETE CASCADE,
    subject            TEXT,
    description        TEXT,
    deadline           TEXT,
    status             TEXT DEFAULT 'active',   -- 'active' або 'completed'
    result_description TEXT,
    created_at         TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);


-- ── Таблиця результатів тестів ────────────────────────────────
-- score — кількість правильних відповідей із total_questions
CREATE TABLE IF NOT EXISTS quiz_results (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT REFERENCES users(id) ON DELETE CASCADE,
    topic           TEXT,
    score           INTEGER,
    total_questions INTEGER,
    created_at      TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);


